function BorderLines({
  color = "#C8A46B",
  inset = 0,
  cornerSize = 70,
  cornerGap = 12,
  thickness = 1,
  opacity = 1,
}) {
  const gap = `calc(${cornerSize}px + ${cornerGap}px)`;

  const lineStyle = {
    backgroundColor: color,
    opacity,
  };

  return (
    <div
      className="pointer-events-none absolute"
      style={{ inset: `${inset}px` }}
    >
      {/* Top */}
      <div
        className="absolute top-0"
        style={{
          ...lineStyle,
          left: gap,
          right: gap,
          height: thickness,
        }}
      />

      {/* Bottom */}
      <div
        className="absolute bottom-0"
        style={{
          ...lineStyle,
          left: gap,
          right: gap,
          height: thickness,
        }}
      />

      {/* Left */}
      <div
        className="absolute left-0"
        style={{
          ...lineStyle,
          top: gap,
          bottom: gap,
          width: thickness,
        }}
      />

      {/* Right */}
      <div
        className="absolute right-0"
        style={{
          ...lineStyle,
          top: gap,
          bottom: gap,
          width: thickness,
        }}
      />
    </div>
  );
}

